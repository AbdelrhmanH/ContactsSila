package app.sila.core.common.crash

/**
 * تلميح فئة عطل مستقر (ADR-0019 — تنسيق التقرير v2): يتيح `Throwable` منصوي —
 * مثل `IosUncaughtException` الذي يحمل اسم `NSException` المستقر
 * (`NSRangeException` مثلاً) — تمرير ذلك المعرف التشخيصي الآمن للمُركِّب،
 * **بديلاً عن الرسالة الحرة** التي حُذفت من التقرير كلياً لأنها قد تحمل نص
 * المستخدم (سبب الاستثناء ورموز المكدس على iOS).
 *
 * العقد: القيمة معرف بنيوي من أعمدة التطوير/المنصة لا من المستخدم، ومع ذلك
 * يتحقق المُركِّب بنياً قبل الإدراج (معرف منقّط صارم) — أي قيمة غير بنيوية
 * تُحذف سطراً كاملاً (deny-by-default).
 */
public interface CrashCategoryHint {

    /** فئة العطل المستقرة، أو null لعدم الإدراج. */
    public val crashCategory: String?
}
