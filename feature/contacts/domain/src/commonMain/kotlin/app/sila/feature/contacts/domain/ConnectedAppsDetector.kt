package app.sila.feature.contacts.domain

/**
 * كاشف التطبيقات المتصلة — عقد نطاقي (T6 · Issue #27 «الربط بأدوات خارجية»).
 *
 * يجيب سؤالاً واحداً: أيّ تطبيقات مراسلة/اتصال مثبتة على الجهاز لجهة الاتصال؟
 * شاشة التفاصيل تُظهر أزرار الفيديو/الرسائل للتطبيقات الموجودة فقط.
 *
 * - **Android:** استعلام `PackageManager.getInstalledPackages` المحدود (بلا
 *   `QUERY_ALL_PACKAGES` — الحزم المرشحة حصراً) — لا وصول شبكي إطلاقاً.
 * - **iOS:** `canOpenURL` مع مخططات مصرَّح بها في `Info.plist`
 *   (`LSApplicationQueriesSchemes` — الحد الأعظمي 50 مخططاً).
 *
 * النتيجة لحظية وقابلة للتخزين المؤقت في الـ ViewModel — لا Flow حصراً (الاكتشاف
 * عملية نادرة نسبياً عند فتح شاشة التفاصيل).
 */
interface ConnectedAppsDetector {

    /**
     * @return التطبيقات المتصلة المتاحة فعلاً على الجهاز (فارغة = لا شيء مثبت أو
     *   انعدام الكشف — الواجهة تعرض الأزرار الأساسية حصراً حينئذٍ).
     */
    suspend fun detect(): List<ConnectedApp>
}

/** تطبيق متصل مُكتشَف — [id] مستقر عبر المنصتين لأغراض العرض والأيقونة. */
data class ConnectedApp(
    /** معرّف مستقر: `whatsapp` / `telegram` (قائمة مغلقة موثقة في المواصفة 03). */
    val id: String,
    /** مخطط الاتصال/الرسالة الأساسي — يُبنى الرابط الكامل في العرض بترقيم الجهة. */
    val scheme: String,
)
