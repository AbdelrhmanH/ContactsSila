package app.sila.feature.contacts.domain.onboarding

/**
 * حالة صلاحية جهات الاتصال أثناء التهيئة الأولى — مطابقة لمصفوفة الأذونات في Issue #20 (تقرير D4،
 * المرحلة 1: طلب واحد فقط لصلاحية جهات الاتصال ضمن حد الطلبات ≤ 2، دون أي صلاحيات إشعارات)
 * وبالامتثال لـ ADR-0009 و ADR-0010.
 *
 * ملاحظة توفيق عند الدمج (Rebase note): تعمل مهمة T1 بالتوازي على تعريف
 * `ContactsPermissionState` في طبقة domain لهذه الميزة نفسها؛ يجب توحيد التعدادين عند دمج
 * الخططين. لا يُعدَّل هنا أي ملف من ملفات T1.
 */
enum class OnboardingPermissionState {
    /** لم يُطلب بعد أو لم يرد المستخدم. */
    NOT_DETERMINED,

    /** كامل الصلاحية (Android: GRANTED / iOS: .authorized). */
    GRANTED,

    /** رفض لمرة واحدة — يمكن إعادة الطلب صراحة (ضمن حد الطلبات ≤ 2). */
    DENIED,

    /** رفض نهائي — لا يُعاد الطلب تلقائياً أبداً؛ الطريق الوحيد فتح إعدادات النظام. */
    DENIED_FOREVER,

    /** iOS .limited — قائمة جزئية؛ توسيع الوصول (iOS 18) يثير حكم إعادة المزامنة حسب ADR-0010. */
    LIMITED,

    /** تخطى المستخدم الصلاحية — يكمل كضيف مع سجل فارغ وباختصار إلى إعدادات التطبيق. */
    SKIPPED
}
