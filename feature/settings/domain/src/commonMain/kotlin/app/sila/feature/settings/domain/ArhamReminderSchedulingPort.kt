package app.sila.feature.settings.domain

/**
 * منفذ إعادة الجدولة الفورية للتذكير (S2-13 · تذكرة #71):
 * الواجهة الوحيدة التي تعتمدها طبقة العرض (`SettingsViewModel`) عند تغيير تفضيلات
 * تؤثر على موعد تذكير أرحام اليومي (الميزة، الوقت المفضل، ساعات الهدوء) — بعد نجاح
 * الكتابة تُستَدعى [rescheduleFromNow] فتعاد خطة الإطلاق من `now` حتماً دون انتظار
 * إقلاع عمليةٍ لاحق (`docs/features/07-ringtones-preferences.md` §ب «أثر فوري»).
 *
 * التنفيذ حصراً في `sharedLogic` عبر منفذَي المنصة (نمط المنفذ — ADR-0016):
 * أندرويد يدعو عبر `ArhamReminderDispatch`، وiOS عبر `IosArhamReminderDispatch`
 * (بفارقه الموثّق: تعطيل الميزة يُلغي الطلب المعلّق فوراً — لا مستقبِل إقلاع
 * يعيد التقييم). المنفذ هنا حملٌ لا قرار: القرار نفسه في
 * `PlanArhamDailyNotificationUseCase` حصراً (يمنع قرارات منصّية مكررة — O-7)،
 * ولا وصول منصّي مباشر من هذه الميزة (عهد واجهات المنفذ — AGENTS.md).
 */
interface ArhamReminderSchedulingPort {

    /**
     * يعيد جدولة الإطلاق اليومي من اللحظة الحالية وفق التفضيلات آنذاك:
     * الميزة مفعّلة ⇒ موعد جديد وفق الخطة؛ معطّلة ⇒ لا جدولة (وتُلغى المعلّقة على iOS).
     * الاستدعاء idempotent — إعادة نفس الموعد تستبدل المعلّق ولا تتراكم (§M).
     */
    suspend fun rescheduleFromNow()
}
