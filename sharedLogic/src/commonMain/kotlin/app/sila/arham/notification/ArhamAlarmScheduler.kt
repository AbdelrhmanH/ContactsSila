package app.sila.arham.notification

/**
 * عقد جدولة تذكير أرحام اليومي (T8-08 أندرويد · T8-12 iOS · D2 المصادَق): نقطةُ
 * الالتقاء الوحيدة بين المنطق المشترك وجدولة المنصة — كل مَن يريد (إعادة) جدولة
 * الإطلاق اليومي يستدعي `scheduleAt` ولا يعرف آلية المنصة (أندرويد: `AlarmManager`
 * غير الدقيق؛ iOS: `UNUserNotificationCenter` بزنّاد يومي متكرر — خطة سطر 552).
 *
 * **D2 — بلا إنذارات دقيقة:** التنفيذان غير دقيقان عمداً (أندرويد `setAndAllowWhileIdle`؛
 * iOS `UNCalendarNotificationTrigger` على الوقت الفعّال) — لا وعداً بوقتٍ محدد قط.
 * الموعد المفقود يُعاد حسابه عند أقرب فرصة لاحقة (تشغيل عملية/تغيير وقت/تفضيل — D2 §8:
 * الجدولة مشتقة من Room والتفضيلات عند كل إطلاق).
 */
interface ArhamAlarmScheduler {

    /**
     * يجدول الإطلاق التالي عند لحظة معيّنة (epoch millis). الاستدعاءات المتتابعة
     * **تستبدل** الموعد السابق ولا تتراكم فوقه (ميزانية ≤ 1/يوم — §M).
     */
    fun scheduleAt(fireAtMillis: Long)
}
