package app.sila.arham.emergency

/**
 * نقطة الإدخال الخاصة بـ iOS لإعادة الاتصال داخل حلقة الطوارئ (T8-13 · §L.6/§N.3).
 *
 * خلافاً لأندرويد (FGS يُدير الحلقة ذاتياً CALL→IDLE→5ث→CALL)، فإن iOS **لا يملك حلقةً ذاتية**:
 * كل محاولة تالية تحتاج تأكيداً يدوياً من المستخدم في الواجهة (T8-14)، وكل تأكيد يستدعي
 * [placeCall] لإعادة فتح `tel:` بعد أن يسجّل المحاولة عبر `RecordEmergencyAttemptUseCase`.
 *
 * العقد **ids-only حصراً**: يُستلم `contactId` فقط، ويُعاد قراءة الرقم من Room لحظة الطلب
 * (مرآة `AndroidEmergencyRingingService.runRingingLoop` التي تقرأ الرقم في كل دورة،
 * ومرآة إجراء الاتصال في الودجت) — لا تمرّر أرقاماً أو أسماء بين الطبقات (ADR-0006).
 */
interface IosEmergencyCallPlacer {

    /**
     * يفتح اتصالاً `tel:` الآن لجهة الإسعاف [contactId] (بعد إعادة القراءة من Room).
     * الهدوء عند الفشل: جهة محذوفة / بلا أرقام / `tel:` غير متاح (iPad أو بلا شريحة) ←
     * يُسجَّل النوع فقط بلا بيانات شخصية (§O.5) ولا يُطرح أي استثناء.
     */
    fun placeCall(contactId: Long)
}
